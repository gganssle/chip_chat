"""Every table, in the order `snowflake/sql/` creates them.

The order is load-bearing in the DDL rather than decorative: a ``FOREIGN KEY``
needs the table it references to exist, so ``demo_visitors`` is created before
``persona_fixtures`` points at it.
"""


def table(name: str) -> Table:
    """Return one table by name.

    Args:
        name: An unqualified table name, in any case.

    Returns:
        The declaration.

    Raises:
        KeyError: If no table is called that.
    """
    for candidate in TABLES:
        if candidate.name.upper() == name.upper():
            return candidate
    raise KeyError(f"no table {name!r} in CHIP_CHAT")


def policy(name: str) -> Policy:
    """Return one row access policy by name.

    Args:
        name: A policy name, in any case.

    Returns:
        The declaration.

    Raises:
        KeyError: If no policy is called that.
    """
    for candidate in POLICIES:
        if candidate.name.upper() == name.upper():
            return candidate
    raise KeyError(f"no row access policy {name!r} in CHIP_CHAT")


def tables_in(schema_name: SchemaName) -> Iterator[Table]:
    """Yield the tables of ``schema_name``, in :data:`TABLES` order."""
    for candidate in TABLES:
        if candidate.schema == schema_name:
            yield candidate


def visitor_scoped() -> Iterator[Table]:
    """Yield every table the :data:`DEMO_ID` rule applies to."""
    for candidate in TABLES:
        if candidate.visitor_scoped:
            yield candidate


def columns_of(name: str) -> tuple[str, ...]:
    """Return one table's column names, in declaration order."""
    return table(name).column_names()
