"""The tables, as data. RFC-001 §04 on one side, `snowflake/sql/` on the other.

`chip_chat.snowflake.account` does this for roles, warehouses and schemas and
says why: `snowflake/sql/` is the only thing that creates anything, and this
module creates nothing. What it adds is a third party to an argument that
otherwise has two -- RFC-001 §04 fixes the schema, `sql/06_catalogue.sql`
through `sql/08_marts.sql` spell it as DDL, and `tests/test_schema_layout.py`
holds the second to the first through this.

Four things are declared here that the DDL cannot check about itself:

**Which columns RFC-001 §04 actually prints.** :attr:`Table.rfc` is §04
transcribed, and it is the whole of "match the schema exactly" as a test. A
column that disappears from a ``CREATE TABLE`` fails `make ci` rather than
being noticed by whoever writes the query that needed it.

**Why every other column is there.** :attr:`Table.additions` pairs each column
§04 does not print with the reason it exists, and the test asserts that a
table's columns are exactly ``rfc | additions`` -- so a column added without an
argument is a failure, and the argument is a string somebody had to write. Ten
of them are #42's, every one already generated by ``chip_chat.data_gen`` and
conformed by silver. The rest belong to the three tables §04 does not print at
all, which arrived with #46 and whose :attr:`Table.rfc` is therefore empty:
``rewards`` and ``rewards_terms`` in CATALOGUE, because a procedure cannot
validate a redemption against a catalogue that is not here nor accrue at a rate
nobody published, and ``action_receipts`` in ACCOUNTS, because idempotency
needs somewhere durable to remember that a retry key has been spent. An empty
``rfc`` is the loud case: every single column of such a table has to carry its
own argument.

**Which tables are visitor-scoped.** :attr:`Table.visitor_scoped` is the
demo_id rule, and :data:`EXEMPT` is the two tables it does not apply to, with
the reason beside each. `sql/09_audit.sql` asks the live account the same
question and defaults to deny in the same direction; the two are not redundant,
because this one sees the tables somebody wrote down and that one sees the
tables nobody did.

**Which policy guards each of them.** :attr:`Table.policy` names the row access
policy `sql/10_policies.sql` attaches, and :data:`POLICIES` is the two of them
with what each promises about a session that has bound nobody.
`tests/test_row_access_policies.py` compares the two lists in both directions,
which is issue #43's coverage requirement: a visitor-scoped table added without
a policy fails `make ci`, and so does a policy attached to a table nobody
declared visitor-scoped.

The types are not §04's -- §04 fixes no types. They are the producing layer's:
silver's ``DECIMAL(10,2)`` for money and ``DECIMAL(8,2)`` for calories in
CATALOGUE and ACCOUNTS, gold's ``DECIMAL(12,2)``, ``DECIMAL(5,4)`` and
``DECIMAL(12,6)`` in MARTS. A publish (#39) that has to cast is a publish that
had to decide, and nobody wrote that decision down.
"""

