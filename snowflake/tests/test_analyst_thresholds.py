"""When the account lane declines, which RFC-001 §10 makes a requirement.

`chip_chat.snowflake.analyst` is the one sentence in that table -- *a Cortex
Analyst timeout or low confidence returns "I can't answer that reliably" and
never a fallback hand-written query* -- written as a function, and this is where
the sentence gets held to. Free and offline: :func:`~chip_chat.snowflake.analyst.decide`
makes no call, so every branch of it is reachable from a dictionary.

The responses below are the real shapes, trimmed. They were taken from
``/api/v2/cortex/analyst/message`` against this account on 2026-08-27: the
verified path returns a CTE per logical table, the generated path returns
``SELECT * FROM SEMANTIC_VIEW(...)``, and the path with no answer returns
suggestions and no ``sql`` part at all.

The tests that matter most are the ones about SQL that came back and was
refused anyway. A refusal on a timeout is easy and nobody gets it wrong. A
refusal of a statement that arrived, parsed and would have run is the one
RFC-001 §10 is actually about, because that is the moment a fallback query
looks reasonable.
"""

import pytest

from chip_chat.snowflake import account, analyst, semantic

VERIFIED_SQL = (
    "WITH __points AS (SELECT delta AS point_change FROM "
    "CHIP_CHAT.ACCOUNTS.LOYALTY_LEDGER) SELECT SUM(l.point_change) AS "
    "points_balance FROM __points AS l -- Generated by Cortex Analyst"
)
GENERATED_SQL = (
    "SELECT * FROM SEMANTIC_VIEW(CHIP_CHAT.ACCOUNTS.ACCOUNT_LANE METRICS "
    "last_order_at WHERE store_city = 'NH Town 1')"
)


def response(*content: dict) -> dict:
    """Wrap content parts the way the REST API wraps them."""
    return {"message": {"role": "analyst", "content": list(content)}}


def sql_part(statement: str, *, verified: str = "") -> dict:
    """One ``sql`` content part, with or without a verified query behind it."""
    confidence = {"verified_query_used": {"name": verified} if verified else None}
    return {"type": "sql", "statement": statement, "confidence": confidence}


# ---------------------------------------------------------------------------
# The thresholds
# ---------------------------------------------------------------------------


def test_an_unset_environment_is_the_argued_default() -> None:
    """Doing nothing gets the defaults, not an unthresholded lane."""
    thresholds = analyst.Thresholds.from_env({})
    assert thresholds.timeout_seconds == analyst.DEFAULT_TIMEOUT_SECONDS
    assert thresholds.min_confidence == analyst.CONFIDENCE[analyst.Path.GENERATED]


def test_the_default_deadline_fits_inside_the_warehouses() -> None:
    """The Analyst call and the SQL it produces both have to fit in one turn.

    The serving warehouse kills a statement at sixty seconds; this bounds the
    hop before it. A deadline at or above the warehouse's would mean the lane
    was still waiting when the query it is waiting for had already been killed.
    """
    serving = next(
        warehouse
        for warehouse in account.WAREHOUSES
        if warehouse.name == account.SERVING_WAREHOUSE
    )
    assert serving.statement_timeout_seconds > analyst.DEFAULT_TIMEOUT_SECONDS


@pytest.mark.parametrize(
    "variable",
    [analyst.TIMEOUT_VARIABLE, analyst.MIN_CONFIDENCE_VARIABLE],
)
def test_a_threshold_that_does_not_parse_fails_at_startup(variable: str) -> None:
    """A misspelled number that quietly kept the default is worse than a crash.

    The same argument as `vision.matcher.SlotRules.from_env`: a lane tuned
    against a threshold nobody set is a measurement of the wrong thing.
    """
    with pytest.raises(ValueError, match=variable):
        analyst.Thresholds.from_env({variable: "quite high"})


def test_a_deadline_of_zero_is_refused() -> None:
    """It would decline every question before asking it, which is not a policy."""
    with pytest.raises(ValueError, match="decline every question"):
        analyst.Thresholds.from_env({analyst.TIMEOUT_VARIABLE: "0"})


def test_a_floor_outside_the_ladder_is_refused() -> None:
    """1.5 is not "stricter than verified"; it is a lane that never answers."""
    with pytest.raises(ValueError, match=r"\[0, 1\]"):
        analyst.Thresholds.from_env({analyst.MIN_CONFIDENCE_VARIABLE: "1.5"})


def test_both_thresholds_are_read_from_the_environment() -> None:
    """#45's fourth criterion: configured, not compiled in."""
    thresholds = analyst.Thresholds.from_env(
        {analyst.TIMEOUT_VARIABLE: "4", analyst.MIN_CONFIDENCE_VARIABLE: "1"}
    )
    assert thresholds.timeout_seconds == 4.0
    assert thresholds.min_confidence == 1.0
    assert thresholds.admits(analyst.Path.VERIFIED)
    assert not thresholds.admits(analyst.Path.GENERATED)


# ---------------------------------------------------------------------------
# Answering
# ---------------------------------------------------------------------------


def test_a_verified_answer_is_returned_with_the_query_that_matched() -> None:
    """The top rung, and the one a person wrote and a test covers."""
    decision = analyst.decide(
        response(sql_part(VERIFIED_SQL, verified="POINTS_BALANCE")),
        elapsed_seconds=2.3,
    )
    assert decision.answered
    assert decision.path is analyst.Path.VERIFIED
    assert decision.confidence == 1.0
    assert decision.verified_query == "POINTS_BALANCE"
    assert decision.sql == VERIFIED_SQL


def test_generated_sql_is_answered_by_default() -> None:
    """Refusing everything unverified would refuse most of PRD A2.

    Aggregates and time ranges are the reason Cortex Analyst is in the design
    at all, and nobody can enumerate them in advance.
    """
    decision = analyst.decide(response(sql_part(GENERATED_SQL)), elapsed_seconds=4.1)
    assert decision.answered
    assert decision.path is analyst.Path.GENERATED
    assert decision.sql == GENERATED_SQL


def test_a_verified_only_floor_refuses_generated_sql() -> None:
    """A supported position, and what a demo in front of an audience wants."""
    decision = analyst.decide(
        response(sql_part(GENERATED_SQL)),
        elapsed_seconds=4.1,
        thresholds=analyst.Thresholds(min_confidence=1.0),
    )
    assert not decision.answered
    assert not decision.sql
    assert "floor" in decision.reason


def test_the_interpretation_survives_onto_the_decision() -> None:
    """Analyst restates the question, and a trace is better for having it."""
    decision = analyst.decide(
        response(
            {"type": "text", "text": "This is our interpretation of your question:"},
            sql_part(GENERATED_SQL),
        ),
        elapsed_seconds=1.0,
    )
    assert decision.interpretation.startswith("This is our interpretation")


