def test_a_slow_answer_is_declined_even_though_it_arrived() -> None:
    """A turn that took too long has failed as a conversation whatever it said."""
    decision = analyst.decide(
        response(sql_part(VERIFIED_SQL, verified="POINTS_BALANCE")),
        elapsed_seconds=30.0,
    )
    assert not decision.answered
    assert decision.path is analyst.Path.UNAVAILABLE
    assert not decision.sql
    assert "deadline" in decision.reason


def test_nothing_coming_back_is_declined_rather_than_raised() -> None:
    """A lane may fail; the conversation may not fail with it."""
    decision = analyst.decide(None, elapsed_seconds=0.2)
    assert not decision.answered
    assert decision.path is analyst.Path.UNAVAILABLE


def test_suggestions_without_sql_are_a_refusal_and_keep_the_suggestions() -> None:
    """Analyst offering other questions IS Analyst declining this one.

    The suggestions are worth carrying: they are the model saying what it does
    cover, which is a better thing to put in front of a visitor than silence.
    """
    decision = analyst.decide(
        response(
            {
                "type": "suggestions",
                "suggestions": ["what have i spent this year", "what do i order most"],
            }
        ),
        elapsed_seconds=3.0,
    )
    assert not decision.answered
    assert decision.path is analyst.Path.SUGGESTED
    assert decision.suggestions == (
        "what have i spent this year",
        "what do i order most",
    )


def test_a_query_that_names_a_visitor_is_refused_even_when_it_would_run() -> None:
    """The guard that is not about confidence at all.

    No tool signature carries a visitor identifier (RFC-001 §06) and the model
    is told never to filter on one, so a statement that does is either an
    invented literal or a reach at somebody else's rows. Both are refusals.
    """
    decision = analyst.decide(
        response(
            sql_part(
                "SELECT SUM(total) FROM CHIP_CHAT.ACCOUNTS.orders "
                "WHERE demo_id = 'demo-0001'"
            )
        ),
        elapsed_seconds=2.0,
    )
    assert not decision.answered
    assert not decision.sql
    assert "demo_id" in decision.reason


def test_a_query_that_leaves_the_model_is_refused() -> None:
    """The bound is the point of #45, and it is checked rather than trusted."""
    decision = analyst.decide(
        response(
            sql_part(
                "SELECT SUM(m.calories) FROM CHIP_CHAT.ACCOUNTS.order_items li "
                "JOIN CHIP_CHAT.CATALOGUE.item_prices m ON m.item_id = li.item_id"
            )
        ),
        elapsed_seconds=2.0,
    )
    assert not decision.answered
    assert "item_prices" in decision.reason


def test_a_query_against_another_semantic_view_is_refused() -> None:
    """There is one account lane, and a second view would be a second boundary."""
    decision = analyst.decide(
        response(sql_part("SELECT * FROM SEMANTIC_VIEW(CHIP_CHAT.MARTS.SOMETHING)")),
        elapsed_seconds=2.0,
    )
    assert not decision.answered
    assert "SOMETHING" in decision.reason


@pytest.mark.parametrize(
    "statement",
    [
        "DELETE FROM CHIP_CHAT.ACCOUNTS.orders",
        "UPDATE CHIP_CHAT.ACCOUNTS.loyalty_ledger SET delta = 1000",
        "SELECT 1 FROM CHIP_CHAT.ACCOUNTS.orders; DROP TABLE CHIP_CHAT.ACCOUNTS.orders",
    ],
)
def test_anything_that_is_not_a_single_read_is_refused(statement: str) -> None:
    """CHIP_CHAT_READ would be refused these anyway. Declining first is cheaper.

    And it is the difference between a span that says what the lane declined
    and a Snowflake error nobody attributes to the account lane.
    """
    decision = analyst.decide(response(sql_part(statement)), elapsed_seconds=1.0)
    assert not decision.answered


def test_every_table_the_view_models_is_allowed_through() -> None:
    """The guard bounds; it must not also block what the model does carry."""
    for table in semantic.LOGICAL_TABLES:
        qualified = f"CHIP_CHAT.{table.schema}.{table.table}"
        assert not analyst.reads_only_the_view(f"SELECT 1 FROM {qualified}"), (
            f"{qualified} is in the semantic view and the guard refuses it"
        )


def test_a_refusal_never_carries_sql() -> None:
    """RFC-001 §10's actual prohibition, as a property of every refusal path.

    "Never a fallback hand-written query" is easy to keep by not writing one.
    It is lost the other way: a decision that declines and still hands its
    caller a statement is a fallback query with extra steps.
    """
    declines = (
        analyst.decide(None, elapsed_seconds=0.1),
        analyst.decide(response(sql_part(VERIFIED_SQL)), elapsed_seconds=99.0),
        analyst.decide(response({"type": "suggestions"}), elapsed_seconds=1.0),
        analyst.decide(
            response(sql_part("SELECT 1 FROM CHIP_CHAT.MARTS.customer_360")),
            elapsed_seconds=1.0,
        ),
        analyst.decide(
            response(sql_part(GENERATED_SQL)),
            elapsed_seconds=1.0,
            thresholds=analyst.Thresholds(min_confidence=1.0),
        ),
    )
    for decision in declines:
        assert not decision.answered
        assert decision.sql == ""
        assert decision.reason


def test_the_refusal_is_the_sentence_the_rfc_wrote() -> None:
    """One sentence, whatever declined and why. The reason is for the span."""
    assert analyst.REFUSAL == "I can't answer that reliably"
