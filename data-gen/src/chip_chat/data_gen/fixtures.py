"""Which customers are worth showing a visitor, and the sentence that says why.

Issue #26. The population generated by issue #25 contains five hundred
customers and seven archetypes; this picks out the handful of them a visitor is
actually assigned on arrival, and writes each one's story from their own
history.

The ticket states the rule this module is arranged around, and it is absolute:

    If a fixture cannot demonstrate its own metric, it is not finished.

So a customer becomes a fixture only by clearing the bounds their archetype
sets on their own defining behaviour. The Regular needs a usual so dominant
that reordering in one turn is obviously possible; the Lapsed Customer needs
months of silence *and* unredeemed points, or PRD requirement P3 has nothing to
surface; the Explorer needs orders varied enough that no usual stands out,
which is the point rather than a defect — it is what exercises the honest
"I am not sure what your usual is" path. The bounds are in ``population.toml``
beside the archetype and every one of them is checked here. Nothing else can
make a customer a fixture.

**Selection never invents and never pads.** An archetype with fewer qualifying
customers than :attr:`~chip_chat.data_gen.config.GeneratorConfig.fixtures_per_persona`
contributes the ones it has. A sixty-customer population honestly yields fewer
fixtures than a five-hundred-customer one, and saying so is better than
promoting a customer who fails their own test to make a count come out right —
that is precisely how a demo ends up assigning a visitor "the Regular" who has
no usual. Whether the *shipped* population is thin in this way is a question
about the shipped config, and ``test_fixtures.py`` asks it.

**Selection reads no editable column.** The facts below come from ``orders``,
``order_items`` and ``loyalty_ledger``, plus ``demo_visitors.persona_id`` —
which is the one column of that table a visitor cannot edit. The three they can
edit (``display_name``, ``home_store_override``, ``stated_preferences``) are
never read, so a visitor renaming themselves cannot change who the fixtures
are or what their narratives say. That is the same containment RFC-001
section 04 requires of the gold marts, and ``test_fixtures.py`` asserts it by
mutating those three columns and re-selecting.

**This is not the ``usual_order`` mart.** :attr:`CustomerFacts.usual_share` is
a blunt count — the share of a customer's orders that are their commonest
basket — and the mart of RFC-001 section 04 computes a ``confidence`` its own
way in Databricks. The two are deliberately not named the same thing. What
makes them agree about a fixture is not a shared definition but the selection:
customers are taken from the *extremes*, a Regular above ninety per cent and an
Explorer below fifteen, so any sane definition of confidence puts them on the
same sides of the line.
"""

